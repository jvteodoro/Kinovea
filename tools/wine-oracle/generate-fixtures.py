#!/usr/bin/env python3
"""Create deterministic, synthetic RGB fixtures for the Wine GUI scenarios."""

from __future__ import annotations

import hashlib
import json
import struct
import sys
import zlib
from pathlib import Path


def color(x: int, y: int, width: int, height: int) -> tuple[int, int, int]:
    # Broad color bars and an asymmetric diagonal make orientation and basic
    # visible presentation easy to inspect without relying on real media.
    band = min(5, (x * 6) // width)
    palette = ((235, 40, 35), (40, 205, 65), (245, 220, 25),
               (30, 55, 220), (220, 35, 190), (25, 210, 215))
    r, g, b = palette[band]
    diagonal = abs(y - (height // 8 + x * 3 // 8)) <= max(2, width // 160)
    if diagonal:
        return 250, 250, 250
    if x > width * 3 // 4 and y > height * 2 // 3:
        cell = max(8, min(width, height) // 24)
        if (x // cell + y // cell) % 2:
            return 245, 245, 245
        return 25, 25, 25
    return r, g, b


def rows(width: int, height: int):
    for y in range(height):
        yield bytes(channel for x in range(width) for channel in color(x, y, width, height))


def png(path: Path, width: int, height: int) -> None:
    def chunk(tag: bytes, payload: bytes) -> bytes:
        return struct.pack(">I", len(payload)) + tag + payload + struct.pack(">I", zlib.crc32(tag + payload) & 0xffffffff)

    raw = b"".join(b"\0" + row for row in rows(width, height))
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def bmp(path: Path, width: int, height: int) -> None:
    row_bytes = width * 3
    padding = (-row_bytes) % 4
    pixel_data = bytearray()
    for row in reversed(list(rows(width, height))):
        # BMP stores pixels in BGR order and the rows bottom-up.
        pixel_data.extend(row[i + 2] for i in range(0, row_bytes, 3))
        pixel_data.extend(row[i + 1] for i in range(0, row_bytes, 3))
        pixel_data.extend(row[i] for i in range(0, row_bytes, 3))
        pixel_data.extend(b"\0" * padding)
    file_size = 54 + len(pixel_data)
    file_header = struct.pack("<2sIHHI", b"BM", file_size, 0, 0, 54)
    dib = struct.pack("<IIIHHIIIIII", 40, width, height, 1, 24, 0, len(pixel_data), 2835, 2835, 0, 0)
    path.write_bytes(file_header + dib + pixel_data)


def record(path: Path, image_format: str, width: int, height: int) -> dict:
    return {"filename": path.name, "format": image_format, "dimensions": f"{width}x{height}", "sizeBytes": path.stat().st_size, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "provenance": "Generated by tools/wine-oracle/generate-fixtures.py; synthetic RGB shapes, no third-party media."}


def main() -> int:
    if len(sys.argv) != 2:
        print(f"usage: {Path(sys.argv[0]).name} OUTPUT_DIRECTORY", file=sys.stderr)
        return 2
    output = Path(sys.argv[1]).expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    png_path = output / "synthetic-rgb-1280x720.png"
    bmp_path = output / "synthetic-rgb-640x480.bmp"
    png(png_path, 1280, 720)
    bmp(bmp_path, 640, 480)
    manifest = {"schemaVersion": 1, "fixtures": [record(png_path, "PNG RGB", 1280, 720), record(bmp_path, "BMP 24-bit RGB", 640, 480)]}
    (output / "fixtures.v1.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
